from playwright.sync_api import sync_playwright
OUT = '/home/claude/roma/test/shots/'
errors = []
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, has_touch=True, is_mobile=True)
    page = ctx.new_page()
    page.on('console', lambda m: errors.append(f'[{m.type}] {m.text}') if m.type == 'error' and 'ERR_FAILED' not in m.text else None)
    page.on('pageerror', lambda e: errors.append(f'[pageerror] {e}'))
    page.route('**/fonts.googleapis.com/**', lambda r: r.abort())
    page.route('**/fonts.gstatic.com/**', lambda r: r.abort())
    page.goto('file:///home/claude/roma/test/page.html')
    page.wait_for_timeout(300)
    page.evaluate("MAP.init()")
    page.evaluate("""S.newGame({ country: 'carth', rank: 'shog', min: 'chiso', sei: '李', mei: '牧', age: 42, stats: { bu: 80, tou: 90, chi: 75, pol: 50, mi: 70 }, traits: ['kobu'], style: 'bal', diff: 1 }); UI.main('map');""")
    page.wait_for_function("MAP.ready === true", timeout=60000)
    # clash
    page.evaluate("""(() => { const me = S.myOff(); const foe = S.bestGeneral('rome'); window._p = UI.cutin({ kind: 'clash', a: me, b: foe, title: '長平の戦い', sub: '趙軍 4.5万　対　秦軍 6万', dur: 4000 }); })()""")
    page.wait_for_timeout(900)
    page.screenshot(path=OUT + 'c_clash.png')
    page.locator('.cutin').tap(); page.wait_for_timeout(400)
    page.evaluate("""(() => { const me = S.myOff(); window._p = UI.cutin({ kind: 'single', a: me, side: 0, title: '突撃！', sub: '李牧隊（重騎兵）', dur: 4000 }); })()""")
    page.wait_for_timeout(900)
    page.screenshot(path=OUT + 'c_charge.png')
    page.locator('.cutin').tap(); page.wait_for_timeout(400)
    page.evaluate("""(() => { const me = S.myOff(); const foe = S.bestGeneral('rome'); window._p = UI.cutin({ kind: 'single', a: me, side: 0, title: foe.n + '、討ち取ったり！', sub: '敵の総大将を討ち取った！', red: true, dur: 4000 }); })()""")
    page.wait_for_timeout(900)
    page.screenshot(path=OUT + 'c_slay.png')
    page.locator('.cutin').tap(); page.wait_for_timeout(400)
    page.evaluate("""(() => { const me = S.myOff(); const foe = S.bestGeneral('rome'); window._p = UI.cutin({ kind: 'duel', a: me, b: foe, title: me.n + '、' + foe.n + 'を討ち取る！', sub: '一騎打ち', red: true, dur: 4000 }); })()""")
    page.wait_for_timeout(900)
    page.screenshot(path=OUT + 'c_duel.png')
    page.locator('.cutin').tap(); page.wait_for_timeout(400)
    page.evaluate("""(() => { window._p = UI.cutin({ kind: 'banner', title: '勝利', sub: '敵は総崩れとなった', color: '#f3d27a', dur: 4000 }); })()""")
    page.wait_for_timeout(900)
    page.screenshot(path=OUT + 'c_win.png')
    page.locator('.cutin').tap(); page.wait_for_timeout(500)
    print('left', page.evaluate("document.querySelectorAll('.cutin').length"))
    print('errors', errors)
    b.close()
