import json
from playwright.sync_api import sync_playwright
OUT = '/home/claude/roma/test/shots/'
errors = []
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, has_touch=True, is_mobile=True)
    page = ctx.new_page()
    page.on('console', lambda m: errors.append(f'[{m.type}] {m.text}') if m.type == 'error' and 'ERR_FAILED' not in m.text else None)
    page.on('pageerror', lambda e: errors.append(f'[pageerror] {e}'))
    page.route('**/fonts.googleapis.com/**', lambda r: r.abort())
    page.route('**/fonts.gstatic.com/**', lambda r: r.abort())
    page.goto('file:///home/claude/roma/test/page.html')
    page.wait_for_function("typeof GEO !== 'undefined' && GEO.built", timeout=60000)
    page.evaluate("""(() => { S.newGame({ country: 'carth', rank: 'shog', min: 'chiso', sei: '李', mei: '牧', age: 30, stats: { bu: 80, tou: 85, chi: 70, pol: 50, mi: 60 }, traits: ['kobu'], style: 'bal', diff: 1 }); G.me.land.fac.barracks = 2; G.me.gold = 500000; UI.main('army'); })()""")
    page.wait_for_timeout(400)
    page.screenshot(path=OUT + 'a_1tab.png', full_page=False)
    # 割り振りまでスクロールして全体
    page.evaluate("document.querySelector('#allot').scrollIntoView()")
    page.wait_for_timeout(200)
    page.screenshot(path=OUT + 'a_2allot.png')
    # 直属の最初の隊で「移す」
    first = page.locator('.ag[data-g=""] [data-mv]').first
    first.click(); page.wait_for_timeout(200)
    page.screenshot(path=OUT + 'a_3editor.png')
    page.fill('#mv-n', '1500')
    page.locator('.mv-dst [data-dst]').nth(1).click()
    dst = page.evaluate("UI.allotDst")
    tot0 = page.evaluate("S.armyTotal()")
    page.click('[data-go]'); page.wait_for_timeout(300)
    print('moved to', dst, 'total same', page.evaluate("S.armyTotal()") == tot0, 'dst troops', page.evaluate(f"U.sum(G.me.army.sq.filter(s => s.ld === '{dst}'), s => s.n)"))
    # 任せ方：攻勢
    page.locator(f'[data-om="{dst}"][data-mode="attack"]').click(); page.wait_for_timeout(200)
    print('order', page.evaluate(f"G.me.army.orders['{dst}']"))
    page.evaluate(f"document.querySelector('.ag[data-g=\"{dst}\"]').scrollIntoView()")
    page.wait_for_timeout(150)
    page.screenshot(path=OUT + 'a_4moved.png')
    # 私兵募集（数の入力ダイアログ）
    page.evaluate("void UI.runAct('shihei')")
    page.wait_for_timeout(300)
    page.locator('.modal .ch').first.click(); page.wait_for_timeout(300)
    page.screenshot(path=OUT + 'a_5number.png')
    page.locator('.modal .na-q .chip').nth(1).click()
    print('dialog value', page.evaluate("document.querySelector('.modal .numask input[type=number]').value"))
    page.locator('.modal .btn.seal').click(); page.wait_for_timeout(300)
    if page.locator('.modal .btn.seal').count(): page.locator('.modal .btn.seal').first.click()
    page.wait_for_timeout(300)
    pv = page.evaluate("G.me.army.sq.filter(s => s.pv).map(s => s.t + ':' + s.n + '/' + s.max)")
    print('pv squads', pv)
    # 私兵の解散（二度押し）
    page.evaluate("UI.tab('army'); document.querySelector('#allot').scrollIntoView()")
    pvid = page.evaluate("G.me.army.sq.find(s => s.pv).id")
    page.locator(f'[data-mv="{pvid}"]').click(); page.wait_for_timeout(200)
    page.locator('[data-disband]').click(); page.wait_for_timeout(100)
    print('disband label', page.locator('[data-disband]').inner_text())
    page.screenshot(path=OUT + 'a_6disband.png')
    page.locator('[data-disband]').click(); page.wait_for_timeout(300)
    print('pv after disband', page.evaluate("G.me.army.sq.filter(s => s.pv).length"))
    # 市場で兵糧
    f0 = page.evaluate("G.me.food")
    page.evaluate("void UI.runAct('kaimono')"); page.wait_for_timeout(300)
    page.locator('.modal .ch').first.click(); page.wait_for_timeout(300)
    page.screenshot(path=OUT + 'a_7food.png')
    page.locator('.modal .btn.seal').click(); page.wait_for_timeout(300)
    if page.locator('.modal .btn.seal').count(): page.locator('.modal .btn.seal').first.click()
    print('food', f0, '->', page.evaluate("G.me.food"))
    # 合戦：任せた隊が開戦と同時に動く
    page.evaluate("""(() => { G.me.army.sortieAsk = false; G.me.army.sortiePre = 'all'; const o = S.myOff(); const pid = S.adj(G.me.loc).find(q => G.prov[q].o !== o.c) || G.me.loc; const spec = W.buildSpec({ kind: 'field', pid, title: '試し', A: { c: o.c, troops: 20000, cmd: o }, B: { c: 'rome', troops: 18000, cmd: S.bestGeneral('rome') }, me: 'A', role: 'commander' }); HOOK.battle(spec); })()""")
    page.wait_for_timeout(1200)
    page.screenshot(path=OUT + 'a_8deploy.png')
    page.click('#dep-go'); page.wait_for_timeout(800)
    print('delegated in battle', page.evaluate("V.bt.units.filter(u => u.delegate).map(u => u.delegate.n + ':' + u.delegate.mode)"))
    print('ERRORS:', json.dumps(errors[:20], ensure_ascii=False, indent=1))
    b.close()
