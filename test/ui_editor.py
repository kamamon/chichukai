import json
from playwright.sync_api import sync_playwright
OUT = '/home/claude/roma/test/shots/'
errors = []
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, has_touch=True, is_mobile=True)
    page = ctx.new_page()
    page.on('console', lambda m: errors.append(f'[{m.type}] {m.text}') if m.type == 'error' and 'ERR_FAILED' not in m.text else None)
    page.on('pageerror', lambda e: errors.append(f'[pageerror] {e}'))
    page.route('**/fonts.googleapis.com/**', lambda r: r.abort())
    page.route('**/fonts.gstatic.com/**', lambda r: r.abort())
    page.goto('file:///home/claude/roma/test/page.html')
    page.wait_for_timeout(400)
    page.click('#t-new'); page.click('.pick[data-c="carth"]'); page.click('#s-next'); page.click('.pick[data-r="shog"]'); page.click('#s-next')
    page.wait_for_timeout(300)
    page.screenshot(path=OUT + 'ed_1normal.png', full_page=False)
    page.evaluate("document.querySelector('.flow').scrollTop = 900")
    page.wait_for_timeout(100)
    page.screenshot(path=OUT + 'ed_2normal_traits.png')
    # trait picker
    page.click('#e-tpick'); page.wait_for_timeout(300)
    page.screenshot(path=OUT + 'ed_3picker.png')
    page.fill('.tp-search', '騎兵'); page.wait_for_timeout(300)
    page.screenshot(path=OUT + 'ed_4search.png')
    page.locator('.tp:not([disabled])').nth(0).click()
    page.wait_for_timeout(100)
    page.locator('.modal .btn.seal').click(); page.wait_for_timeout(200)
    # tactic picker
    page.click('#e-cpick'); page.wait_for_timeout(300)
    page.screenshot(path=OUT + 'ed_5tactics.png')
    page.locator('.modal .btn.seal').click(); page.wait_for_timeout(200)
    # custom mode
    page.evaluate("document.querySelector('.flow').scrollTop = 0")
    page.click('#e-mode button[data-m="custom"]'); page.wait_for_timeout(200)
    page.screenshot(path=OUT + 'ed_6custom.png')
    page.click('[data-pre="覇王"]'); page.wait_for_timeout(100)
    page.click('#e-call'); page.wait_for_timeout(100)
    page.click('#e-tpick'); page.wait_for_timeout(300)
