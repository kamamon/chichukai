    print('start disabled', page.evaluate("document.querySelector('#e-start').disabled"), page.evaluate("document.querySelector('.bottom-bar .grow').textContent"))
    page.click('#e-start'); page.wait_for_timeout(800)
    for i in range(5):
        if page.locator('.modal .btn.seal').count(): page.locator('.modal .btn.seal').first.click(); page.wait_for_timeout(200)
    st = page.evaluate("({mode: G.mode, custom: G.custom, tr: S.myOff().tr.length, tac: G.me.tac.length, gold: G.me.gold, stats: [S.stat(S.myOff(),'bu'), S.stat(S.myOff(),'tou')]})")
    print(json.dumps(st, ensure_ascii=False))
    page.click('#nav button[data-t="ppl"]'); page.wait_for_timeout(300)
    page.screenshot(path=OUT + 'ed_9ppl.png')
